import {workerRuntimeBuildOptions} from './worker-build-options.mjs';
import {extensionBuildOptions} from './extension-build-options.mjs';
import {execFileSync} from 'node:child_process';
import {build} from 'esbuild';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
execFileSync('node',['scripts/i18n-catalogue.mjs','--check'],{stdio:'inherit'});
await build({entryPoints:['netlify-return/i18n-source.js'],bundle:true,minify:true,outfile:'netlify-return/i18n.js'});
await build(extensionBuildOptions);
await mkdir('dist',{recursive:true});
await build({entryPoints:['public/sw.js'],bundle:true,minify:true,format:'iife',outfile:'dist/sw.js'});
await build({entryPoints:['public/data-workspace.js'],bundle:true,minify:true,format:'esm',outfile:'dist/data-workspace.js'});
await build({entryPoints:['public/app.js'],bundle:true,minify:true,format:'esm',outfile:'dist/app.js'});
execFileSync('python3',['-c',"import zipfile; z=zipfile.ZipFile('dist/retailer-extension.zip','w',zipfile.ZIP_DEFLATED); [z.write('extension/'+f,'offmenu-retailer-extension/'+f) for f in ['manifest.json','popup.html','popup.css','popup.js','README.md']]; z.close()"]);
await build({entryPoints:['public/scanner-worker.js'],bundle:true,minify:true,format:'esm',outfile:'dist/scanner-worker.js'});
const assets={};
assets['data-workspace.js']=await readFile('dist/data-workspace.js','utf8');
assets['data-workspace.html']=await readFile('public/data-workspace.html','utf8');
assets['retailer-extension.zip']=(await readFile('dist/retailer-extension.zip')).toString('base64');
for(const file of ['index.html','style.css','scanner-licenses.txt','recipes.json','afcd-nutrient-details.json','icon.svg','manifest.webmanifest','manifest-ar.webmanifest'])assets[file]=await readFile('public/'+file,'utf8');
assets['sw.js']=await readFile('dist/sw.js','utf8');
assets['scanner-worker.js']=await readFile('dist/scanner-worker.js','utf8');
assets['scanner.wasm']=(await readFile('node_modules/zxing-wasm/dist/reader/zxing_reader.wasm')).toString('base64');
assets['app.js']=await readFile('dist/app.js','utf8');
const template=await readFile('cloud/handler.mjs','utf8');
const release={sourceCommit:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),builtAt:new Date().toISOString()};
await writeFile('cloud/generated.mjs','const ASSETS='+JSON.stringify(assets)+';\nconst RELEASE='+JSON.stringify(release)+';\n'+template);
await build({...workerRuntimeBuildOptions,entryPoints:['cloud/generated.mjs'],bundle:true,minify:true,format:'esm',platform:'browser',outfile:'dist/worker.mjs'});
console.log('Built worker with '+Object.keys(assets).length+' assets');
